\m5_TLV_version 1d: tl-x.org
\m5
   use(m5-1.0)

\SV
   m4_include_lib(['https://raw.githubusercontent.com/os-fpga/Virtual-FPGA-Lab/main/tlv_lib/fpga_includes.tlv'])

   m5_lab()


\TLV
   /board
      /fpga

         |lcd

            @0

               // =================================================
               // RESET
               // =================================================

               $reset = *reset;


               // =================================================
               // LCD REFRESH
               //
               // Makerchip : 1 simulation cycle
               // FPGA      : 10,000 clocks @ 50 MHz
               //
               // 50 MHz / 10,000 = 5,000 Hz
               // One refresh = 200 us
               //
               // One LCD byte:
               // 5 phases x 200 us = 1 ms
               //
               // One complete frame:
               // 38 bytes x 1 ms = ~38 ms
               // =================================================

               m4+fpga_heartbeat($refresh, 1, 10000)


               // =================================================
               // ALL SEQUENTIAL STATE
               // =================================================

               ?$refresh

                  // =================================================
                  // LCD PHASE
                  //
                  // 0 = LOW
                  // 1 = HIGH
                  // 2 = HIGH
                  // 3 = HIGH
                  // 4 = LOW
                  // =================================================

                  $phase[2:0] <=
                     $reset
                     ? 3'd0
                     : ($phase == 3'd4)
                        ? 3'd0
                        : $phase + 3'd1;


                  // =================================================
                  // LCD BYTE INDEX
                  //
                  // 0-4   = LCD initialization
                  // 5-20  = first line
                  // 21    = second line address
                  // 22-37 = second line
                  // =================================================

                  $index[5:0] <=
                     $reset
                     ? 6'd0
                     : ($phase == 3'd4)
                        ? (($index == 6'd37)
                           ? 6'd0
                           : $index + 6'd1)
                        : >>1$index;


                  // =================================================
                  // FRAME COMPLETE
                  //
                  // When the last character has completed,
                  // advance to the next number.
                  // =================================================

                  $number[5:0] <=
                     $reset
                     ? 6'd1
                     : (($phase == 3'd4) &&
                        ($index == 6'd37))
                        ? (($number == 6'd50)
                           ? 6'd1
                           : $number + 6'd1)
                        : >>1$number;


               // =================================================
               // INTEGER SQUARE ROOT
               //
               // floor(sqrt(N))
               //
               // 1..3   -> 1
               // 4..8   -> 2
               // 9..15  -> 3
               // 16..24 -> 4
               // 25..35 -> 5
               // 36..48 -> 6
               // 49..50 -> 7
               // =================================================

               $root[3:0] =
                  ($number >= 6'd49) ? 4'd7 :
                  ($number >= 6'd36) ? 4'd6 :
                  ($number >= 6'd25) ? 4'd5 :
                  ($number >= 6'd16) ? 4'd4 :
                  ($number >= 6'd9)  ? 4'd3 :
                  ($number >= 6'd4)  ? 4'd2 :
                                       4'd1;


               // =================================================
               // NUMBER TO DECIMAL DIGITS
               // =================================================

               $tens[3:0] =
                  $number / 10;

               $ones[3:0] =
                  $number % 10;


               // =================================================
               // LCD DATA
               //
               // Display:
               //
               // N=01 RT=1
               //
               // and second line:
               //
               // SQRT(01)=1
               // =================================================

               $lcd_byte[7:0] =

                  // =================================================
                  // LCD INITIALIZATION
                  // =================================================

                  ($index == 6'd0) ? 8'h38 :   // 8-bit, 2-line
                  ($index == 6'd1) ? 8'h0C :   // Display ON
                  ($index == 6'd2) ? 8'h01 :   // Clear
                  ($index == 6'd3) ? 8'h06 :   // Entry mode
                  ($index == 6'd4) ? 8'h80 :   // First line


                  // =================================================
                  // LINE 1
                  //
                  // "N=01 RT=1       "
                  // =================================================

                  ($index == 6'd5)  ? 8'h4E :   // N
                  ($index == 6'd6)  ? 8'h3D :   // =

                  ($index == 6'd7) ?
                     (8'h30 + $tens) :

                  ($index == 6'd8) ?
                     (8'h30 + $ones) :

                  ($index == 6'd9)  ? 8'h20 :   // space

                  ($index == 6'd10) ? 8'h52 :   // R
                  ($index == 6'd11) ? 8'h54 :   // T
                  ($index == 6'd12) ? 8'h3D :   // =

                  ($index == 6'd13) ?
                     (8'h30 + $root) :

                  ($index == 6'd14) ? 8'h20 :
                  ($index == 6'd15) ? 8'h20 :
                  ($index == 6'd16) ? 8'h20 :
                  ($index == 6'd17) ? 8'h20 :
                  ($index == 6'd18) ? 8'h20 :
                  ($index == 6'd19) ? 8'h20 :
                  ($index == 6'd20) ? 8'h20 :


                  // =================================================
                  // SECOND LINE ADDRESS
                  // =================================================

                  ($index == 6'd21) ? 8'hC0 :


                  // =================================================
                  // LINE 2
                  //
                  // "SQRT(01)=1      "
                  // =================================================

                  ($index == 6'd22) ? 8'h53 :   // S
                  ($index == 6'd23) ? 8'h51 :   // Q
                  ($index == 6'd24) ? 8'h52 :   // R
                  ($index == 6'd25) ? 8'h54 :   // T
                  ($index == 6'd26) ? 8'h28 :   // (

                  ($index == 6'd27) ?
                     (8'h30 + $tens) :

                  ($index == 6'd28) ?
                     (8'h30 + $ones) :

                  ($index == 6'd29) ? 8'h29 :   // )

                  ($index == 6'd30) ? 8'h3D :   // =

                  ($index == 6'd31) ?
                     (8'h30 + $root) :

                  ($index == 6'd32) ? 8'h20 :
                  ($index == 6'd33) ? 8'h20 :
                  ($index == 6'd34) ? 8'h20 :
                  ($index == 6'd35) ? 8'h20 :
                  ($index == 6'd36) ? 8'h20 :

                  8'h20;


               // =================================================
               // LCD ENABLE
               //
               // Enable HIGH during phases 1,2,3
               // =================================================

               $lcd_enable =
                  (($phase >= 3'd1) &&
                   ($phase <= 3'd3));


               // =================================================
               // LCD RS
               //
               // 0 = COMMAND
               // 1 = DATA
               //
               // Commands:
               // 0,1,2,3,4,21
               // =================================================

               $lcd_rs =
                  (($index >= 6'd5) &&
                   ($index != 6'd21));


               // =================================================
               // LCD OUTPUT
               // =================================================

               *out =
                  $lcd_byte;

               *lcd_enable =
                  $lcd_enable;

               *lcd_reset =
                  $lcd_rs;


      // ==========================================================
      // EDGE ARTIX-7
      //
      // Board ID = 2
      // ==========================================================

      m5+board(/board, /fpga, 2, *, ['top: 0, left: -1500, width: 7000, height: 7000'])


   // ============================================================
   // LCD PERIPHERAL
   // ============================================================

   m5+fpga_lcd()


\SV
   endmodule